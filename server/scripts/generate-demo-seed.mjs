#!/usr/bin/env node
/**
 * Generates drizzle/seeds/demo/01_demo_data.sql: a fictional organization with
 * fake people for the public demo. Every value is invented — emails use the
 * reserved example.org domain, phones are 000 numbers and tax ids are prefixed
 * DEMO so they can never match a real codice fiscale.
 *
 * Usage: node scripts/generate-demo-seed.mjs
 */
import { webcrypto as crypto } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DEMO_EMAIL = 'demo@example.org';
export const DEMO_PASSWORD = 'demo-gestionale';

const ORG_ID = 'demo-org';
const NOW = '2026-01-01T09:00:00.000Z';

// Same scheme as src/lib/auth.ts hashPassword (PBKDF2-SHA256, 100k, "salt:hash").
async function hashPassword(password) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const keyMaterial = await crypto.subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveKey']);
  const key = await crypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: 100000, hash: 'SHA-256' },
    keyMaterial,
    { name: 'AES-GCM', length: 256 },
    true,
    ['encrypt', 'decrypt'],
  );
  const raw = new Uint8Array(await crypto.subtle.exportKey('raw', key));
  const b64 = (bytes) => Buffer.from(bytes).toString('base64');
  return `${b64(salt)}:${b64(raw)}`;
}

const sql = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const insert = (table, row) =>
  `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(sql).join(', ')});`;

// Visitors share this account, so it cannot change its password or manage users
// (either would lock everyone else out until the nightly reset).
const DEMO_PERMISSIONS = [
  'dashboard.view', 'people.view', 'people.edit', 'board.view',
  'assemblies.view', 'assemblies.edit', 'convocations.view', 'convocations.edit',
  'timeline.view', 'resignations.view', 'settings.view', 'settings.manage',
  'settings.users.view', 'documents.view', 'documents.generate', 'documents.manage',
];

const FIRST = ['Giulia', 'Marco', 'Sara', 'Luca', 'Chiara', 'Andrea', 'Francesca', 'Matteo', 'Elena', 'Davide',
  'Alessia', 'Simone', 'Martina', 'Federico', 'Valentina', 'Lorenzo', 'Ilaria', 'Tommaso', 'Beatrice', 'Riccardo'];
const LAST = ['Esposito', 'Bianchi', 'Romano', 'Colombo', 'Ricci', 'Marino', 'Greco', 'Bruno', 'Gallo', 'Conti',
  'De Luca', 'Mancini', 'Costa', 'Giordano', 'Rizzo', 'Lombardi', 'Moretti', 'Barbieri', 'Fontana', 'Santoro'];

async function main() {
  const lines = [
    '-- Public demo data. GENERATED by scripts/generate-demo-seed.mjs — do not edit by hand.',
    '-- All people are fictional. Applied after migrations and seeds/common.',
    '',
    insert('organization', {
      id: ORG_ID, name: 'Associazione Demo ETS', short_name: 'Demo ETS', slug: 'demo',
      domain_signup_mode: 'invite_only', is_setup_complete: 1, created_at: NOW,
    }),
    insert('organization_setting', {
      id: `${ORG_ID}-branding`, org_id: ORG_ID, city: 'Torino', max_proxies: 3, created_at: NOW, updated_at: NOW,
    }),
    insert('user', {
      id: 'demo-user', email: DEMO_EMAIL, password: await hashPassword(DEMO_PASSWORD), created_at: NOW, updated_at: NOW,
    }),
    insert('organization_user', {
      id: 'demo-membership', user_id: 'demo-user', org_id: ORG_ID, role: 'admin',
      permissions: JSON.stringify(DEMO_PERMISSIONS), is_owner: 0, joined_at: NOW,
    }),
    '',
  ];

  const people = [];
  for (let i = 0; i < 40; i++) {
    const n = String(i + 1).padStart(3, '0');
    const first = FIRST[i % FIRST.length];
    const last = LAST[(i * 7) % LAST.length];
    const id = `demo-person-${n}`;
    const enrolled = `202${2 + (i % 4)}-${String((i % 12) + 1).padStart(2, '0')}-15`;
    people.push({ id, enrolled, isMember: i < 26 });
    lines.push(insert('person', {
      id, org_id: ORG_ID, first_name: first, last_name: last,
      tax_id: `DEMO${String(i + 1).padStart(12, '0')}`,
      email: `${first}.${last}.${n}@example.org`.toLowerCase().replaceAll(' ', ''),
      phone: `+39 000 000 0${n}`,
      birth_date: `${1970 + (i % 35)}-0${(i % 9) + 1}-1${i % 10}`,
      is_student: i % 5 === 0 ? 1 : 0,
      created_at: NOW, updated_at: NOW,
    }));
  }
  lines.push('');

  for (const p of people) {
    const vp = `${p.id}-vol`;
    lines.push(insert('volunteer_period', {
      id: vp, org_id: ORG_ID, person_id: p.id, status: 'active', enrollment_date: p.enrolled, created_at: NOW,
    }));
    if (p.isMember) {
      lines.push(insert('member_period', {
        id: `${p.id}-mem`, org_id: ORG_ID, person_id: p.id, volunteer_period_id: vp,
        admission_date: p.enrolled, created_at: NOW,
      }));
    }
  }
  lines.push('');

  lines.push(insert('board_generation', {
    id: 'demo-board-2025', org_id: ORG_ID, name: '2025-2027', start_date: '2025-04-01', created_at: NOW,
  }));
  ['president', 'vice_president', 'treasurer', 'secretary', 'councilor'].forEach((role, i) => {
    lines.push(insert('board_member', {
      id: `demo-board-member-${i + 1}`, org_id: ORG_ID, generation_id: 'demo-board-2025',
      person_id: people[i].id, role, created_at: NOW,
    }));
  });
  lines.push('');

  lines.push(insert('assembly', {
    id: 'demo-assembly-2025', org_id: ORG_ID, type: 'ordinary', total_number: 1, reference_number: 1,
    reference_year: 2025, first_call_date: '2025-04-01', location: 'Sede sociale', mode: 'in_person',
    created_at: NOW, updated_at: NOW,
  }));

  const out = join(dirname(fileURLToPath(import.meta.url)), '../drizzle/seeds/demo/01_demo_data.sql');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, lines.join('\n') + '\n');
  console.log(`wrote ${out}`);
}

main();
